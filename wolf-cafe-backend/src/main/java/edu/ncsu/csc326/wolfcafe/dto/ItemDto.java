package edu.ncsu.csc326.wolfcafe.dto;

import jakarta.validation.constraints.NotBlank;
import jakarta.validation.constraints.PositiveOrZero;
import jakarta.validation.constraints.NotNull;
import lombok.AllArgsConstructor;
import lombok.Getter;
import lombok.NoArgsConstructor;
import lombok.Setter;

/**
 * Item for data transfer.  The validation annotations are checked when a
 * controller method marks its @RequestBody parameter with @Valid; a request that
 * breaks them is answered with 400 Bad Request before the service is called.
 *
 * @author CSC 326 Course Staff
 */
@Getter
@Setter
@NoArgsConstructor
@AllArgsConstructor
public class ItemDto {

	/** Item id */
	private Long id;

	/** Item name */
	@NotBlank(message = "Item name is required.")
	private String name;

	/** Item description */
	private String description;

	/** Item price */
	@NotNull(message = "Item price is required.")
	@PositiveOrZero(message = "Item price must be positive.")
	private Double price;

	/** Item amount */
	@NotNull(message = "Item amount is required.")
	@PositiveOrZero(message = "Item amount must be zero or a positive integer.")
	private Integer amount;

	/**
	 * Creates an item without an initial inventory amount.
	 *
	 * <p>This constructor preserves the original item DTO shape used by
	 * existing item clients and tests. The full constructor generated by
	 * {@link AllArgsConstructor} should be used when an amount is available.</p>
	 *
	 * Function was generated by AI after struggling to identify cause of failing test cases.
	 *
	 * @param id item id
	 * @param name item name
	 * @param description item description
	 * @param price item price
	 */
	public ItemDto(Long id, String name, String description, Double price) {
		this(id, name, description, price, 0);
	}

	/**
	 * Creates an item request without an id. The server assigns the id when the
	 * item is persisted.
	 *
	 * @param name item name
	 * @param description item description
	 * @param price item price
	 * @param amount initial inventory amount
	 */
	public ItemDto(String name, String description, Double price, Integer amount) {
		this(null, name, description, price, amount);
	}
}
